package com.elingo.learning.lesson.dto.response;

import io.swagger.v3.oas.annotations.media.Schema;

import java.time.LocalDateTime;

@Schema(description = "Lesson segment information for the admin console")
public record AdminLessonSegmentResponse(

        @Schema(description = "Segment id", example = "11")
        Long id,

        @Schema(description = "Owning lesson id", example = "7")
        Long lessonId,

        @Schema(description = "Start time in milliseconds", example = "1500")
        Integer startMs,

        @Schema(description = "End time in milliseconds", example = "6200")
        Integer endMs,

        @Schema(description = "Original transcript", example = "Hi, can I get a large coffee, please?")
        String transcriptOriginal,

        @Schema(description = "Normalized transcript generated by the server (lowercase, no special chars)",
                example = "hi can i get a large coffee please")
        String transcriptNormalized,

        @Schema(description = "Translation", example = "Xin chào, cho tôi một ly cà phê lớn nhé?")
        String translation,

        @Schema(description = "Creation time", example = "2026-11-20T09:05:00")
        LocalDateTime createdAt,

        @Schema(description = "Last update time", example = "2026-11-20T09:05:00")
        LocalDateTime updatedAt
) {}
